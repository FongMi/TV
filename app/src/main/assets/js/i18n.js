const language = getLanguage(navigator.languages || [navigator.language]);

function getLanguage(languages) {
    for (const tag of languages) {
        const parts = tag.toLowerCase().split('-');
        if (parts[0] === 'en') return 'en';
        if (parts[0] !== 'zh') continue;
        if (parts.includes('hant')) return 'zh-Hant';
        if (parts.includes('hans')) return 'zh-Hans';
        return parts.some(part => ['tw', 'hk', 'mo'].includes(part)) ? 'zh-Hant' : 'zh-Hans';
    }
    return 'en';
}

function t(key, path) {
    const text = translations[language][key];
    return path === undefined ? text : text.replace('{path}', () => path);
}

document.documentElement.lang = language;
document.querySelectorAll('[data-i18n]').forEach(node => node.textContent = t(node.dataset.i18n));
document.querySelectorAll('[data-i18n-placeholder]').forEach(node => node.placeholder = t(node.dataset.i18nPlaceholder));
document.querySelectorAll('[data-i18n-label]').forEach(node => {
    const label = t(node.dataset.i18nLabel);
    node.setAttribute('aria-label', label);
    node.title = label;
});
